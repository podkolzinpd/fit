import type { BodyZoneShape } from './body-progress-geometry'
import type { BodyMapZone } from './body-progress-map'

type PhotoGeometry = Record<BodyMapZone, readonly BodyZoneShape[]>
type SpecificGeometry = Omit<PhotoGeometry, 'arms' | 'legs' | 'back'>

// Paths are traced against the original 952 × 1000 PNGs, not against a mockup.
// cx/cy are interior anchors for each path; the two photos have independent
// anatomy/poses. Image, outline and hit area all use these same coordinates.
function contour(cx: number, cy: number, rx: number, ry: number, path: string): BodyZoneShape {
  return { cx, cy, rx, ry, path }
}

function withBroadZones(zones: SpecificGeometry): PhotoGeometry {
  return {
    ...zones,
    arms: [...zones.biceps, ...zones.triceps, ...zones.forearms],
    legs: [...zones.quadriceps, ...zones.hamstrings, ...zones.calves],
    back: [...zones.upper_back, ...zones.lower_back],
  }
}

