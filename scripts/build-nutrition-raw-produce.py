"""Rebuild the complete USDA FNDDS raw fruit/vegetable slice from a pinned archive.

Usage: python3 scripts/build-nutrition-raw-produce.py /path/to/official.zip [--check]
Only Russian labels/aliases are curated. Nutrient amounts are never hand-entered.
"""
import hashlib
import json
import math
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE_URL = 'https://fdc.nal.usda.gov/fdc-datasets/FoodData_Central_survey_food_json_2024-10-31.zip'
SOURCE_SHA256 = 'dfb06ae7ddc397ccd570b91c14b75438ab2ba39f64f22d321f61d4a52a77f3eb'
OUTPUT = ROOT / 'services/api/src/nutrition-raw-produce.data.ts'


def build(archive_path):
    archive_bytes = Path(archive_path).read_bytes()
    if hashlib.sha256(archive_bytes).hexdigest() != SOURCE_SHA256:
        raise ValueError('The archive does not match the reviewed USDA release')
    with zipfile.ZipFile(archive_path) as archive:
        files = [name for name in archive.namelist() if name.endswith('.json')]
        if len(files) != 1:
            raise ValueError('Expected one official JSON dataset')
        payload = json.loads(archive.read(files[0]))
    rows = [row for row in payload['SurveyFoods']
            if row['description'].lower().endswith(', raw')
            and str(row['foodCode']).startswith(('6', '7'))]
    labels = {}
    for line in (ROOT / 'scripts/data/nutrition-raw-produce-ru.tsv').read_text().splitlines():
        source_id, name, aliases = line.split('\t')
        if int(source_id) in labels or not 2 <= len(name) <= 160:
            raise ValueError('Invalid or duplicate localization')
        labels[int(source_id)] = (name, [alias for alias in aliases.split('|') if alias])
    if set(labels) != {row['fdcId'] for row in rows} or len(rows) != 96:
        raise ValueError('Localization must cover the entire reviewed raw produce slice')
    result = []
    for row in rows:
        nutrients = {item['nutrient']['id']: item for item in row['foodNutrients']}
        values = {}
        for name, nutrient_id, unit, maximum in [('calories', 1008, 'kcal', 1000),
                                               ('protein', 1003, 'g', 100),
                                               ('fat', 1004, 'g', 100),
                                               ('carbs', 1005, 'g', 100)]:
            item = nutrients.get(nutrient_id, {})
            amount = item.get('amount')
            if (not isinstance(amount, (int, float)) or isinstance(amount, bool)
                    or not math.isfinite(amount) or not 0 <= amount <= maximum
                    or item.get('nutrient', {}).get('unitName', '').lower() != unit):
                raise ValueError(f'Missing/invalid nutrient {nutrient_id} for FDC{row["fdcId"]}')
            values[name] = amount
        if sum(values[key] for key in ('protein', 'fat', 'carbs')) > 101:
            raise ValueError('Invalid macro total')
        name, aliases = labels[row['fdcId']]
        result.append({'sourceId': row['fdcId'], 'sourceDescription': row['description'],
                       'foodCode': row['foodCode'], 'name': name, 'aliases': aliases, **values})
    source = {'url': SOURCE_URL, 'sha256': SOURCE_SHA256, 'dataType': 'Survey (FNDDS)',
              'release': '2021-2023 / 2024-10-31', 'basis': '100g',
              'nutrientIds': {'calories': 1008, 'protein': 1003, 'fat': 1004, 'carbs': 1005}}
    return ('// Generated by scripts/build-nutrition-raw-produce.py; do not edit nutrient values.\n'
            '// USDA FNDDS food-code groups 6 (fruit) and 7 (vegetables), descriptions ending in ", raw".\n'
            'export const USDA_RAW_PRODUCE_SOURCE = ' + json.dumps(source, ensure_ascii=False, indent=2)
            + ' as const\n\nexport const USDA_RAW_PRODUCE = [\n'
            + ',\n'.join('  ' + json.dumps(item, ensure_ascii=False) for item in result)
            + '\n] as const\n')


if __name__ == '__main__':
    text = build(sys.argv[1])
    if '--check' in sys.argv[2:]:
        if OUTPUT.read_text() != text:
            raise ValueError('Committed snapshot differs from the reviewed source')
        print('Verified all 96 raw produce records against the pinned USDA archive')
    else:
        OUTPUT.write_text(text)
        print('Generated all 96 raw produce records from the pinned USDA archive')
